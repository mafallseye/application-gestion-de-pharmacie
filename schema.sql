-- Structure de la base « pharmacie ».
-- Création :  mysql -u root -e "CREATE DATABASE pharmacie CHARACTER SET utf8mb4"
--             mysql -u root pharmacie < schema.sql

CREATE TABLE IF NOT EXISTS `user` (
  id INT AUTO_INCREMENT PRIMARY KEY,
  email VARCHAR(255) NOT NULL,
  passworde VARCHAR(255) NOT NULL,
  group_name VARCHAR(255) NOT NULL
) DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS out_stock (
  id INT AUTO_INCREMENT PRIMARY KEY,
  brand_name VARCHAR(255) NOT NULL,
  genetic_name VARCHAR(255) NOT NULL,
  category VARCHAR(255) NOT NULL,
  price VARCHAR(255) NOT NULL,
  quantity VARCHAR(255) NOT NULL,
  expire VARCHAR(255) NOT NULL
) DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS category (
  id INT AUTO_INCREMENT PRIMARY KEY,
  names VARCHAR(255) NOT NULL,
  short_name VARCHAR(255) NOT NULL,
  create_date VARCHAR(255) NOT NULL
) DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS customers (
  id INT AUTO_INCREMENT PRIMARY KEY,
  names VARCHAR(255) NOT NULL,
  addresse VARCHAR(255) NOT NULL,
  telephone VARCHAR(255) NOT NULL,
  fax VARCHAR(255) NOT NULL,
  info VARCHAR(255) NOT NULL
) DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS suppliers (
  id INT AUTO_INCREMENT PRIMARY KEY,
  names VARCHAR(255) NOT NULL,
  addresse VARCHAR(255) NOT NULL,
  telephone VARCHAR(255) NOT NULL,
  fax VARCHAR(255) NOT NULL,
  info VARCHAR(255) NOT NULL
) DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS sales (
  id INT AUTO_INCREMENT PRIMARY KEY,
  customers_name VARCHAR(255) NOT NULL,
  grand_total VARCHAR(255) NOT NULL,
  paid_amount VARCHAR(255) NOT NULL,
  added_date VARCHAR(255) NOT NULL
) DEFAULT CHARSET=utf8mb4;
